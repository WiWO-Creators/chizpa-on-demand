import type { ChizpaService, ServiceCategory } from "./services";

type ServiceSeed = Omit<ChizpaService, "category" | "icon" | "revisions" | "accent">;

const icons: Record<ServiceCategory, ChizpaService["icon"]> = {
  Presentaciones: "presentation",
  Videos: "video",
  Documentos: "document",
  Diseño: "palette",
  Herramientas: "workflow",
};
const accents: ChizpaService["accent"][] = ["purple", "orange", "lavender", "cream"];

function collection(category: ServiceCategory, entries: ServiceSeed[]): ChizpaService[] {
  return entries.map((entry, index) => ({
    ...entry,
    category,
    icon: icons[category],
    revisions: 1,
    accent: accents[index % accents.length],
  }));
}

